for rel, (x1, y1, x2, y2) in boxes_px.items():
    fp = os.path.join(ROOT, rel)
    W, H = Image.open(fp).size
    cx = ((x1 + x2) / 2) / W
    cy = ((y1 + y2) / 2) / H
    w  = (x2 - x1) / W
    h  = (y2 - y1) / H
